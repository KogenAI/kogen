#!/usr/bin/env python3
"""hook_registrations.py — Parse HOOK-MANIFEST headers and generate hook registration JSONs.

Usage:
    python3 templates/generator/hook_registrations.py \
        --hooks-dir harnesses/claude/hooks \
        --output-settings templates/claude-code-settings.json

Algorithm:
    1. Find all .sh files (excluding _test.sh and run-tests.sh) in --hooks-dir.
    2. Parse HOOK-MANIFEST header block (event, matcher, surface, signal, role).
    3. Validate declared signal appears in script body.
    4. Build user_global and per_call_inspector lists.
    5. Emit --output-settings (user_global entries replace manifest-driven hook events;
       non-manifest-driven events preserved verbatim from existing JSON).

Non-manifest-driven hook events (preserved verbatim from existing settings.json):
    PostToolUse, UserPromptSubmit, SessionStart, SessionEnd

These contain inline bash commands that cannot be expressed as hook scripts,
so they are never regenerated by this tool.

Manifest-driven hook events (fully regenerated):
    PreToolUse, SubagentStop, Stop, PostToolUseFailure

Hook ordering within each event:
    Sorted alphabetically by filename for deterministic output.

Pi TS handler parity:
    When --pi-extension-dir is provided, validates that every Pi-targeted hook
    has a matching TypeScript handler in <pi-extension-dir>/src/hooks/.
"""

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

# Minimal per-role hook bundle for OrchestrationLoop.guard_bundle_flag!("claude_code").
# Every loop-invoked codegen-call runs WITHOUT role identity set (no CLAUDE_ROLE/AGENT_TYPE
# export), so AGENT_TYPE-gated role guards and orchestrator-* guards would either be dead
# weight or over-apply (e.g. orchestrator-no-source-edit would deny a loop `developer`
# editing lib/foo.ex). This allowlist keeps ONLY generic, signal:none, role:"*" denial
# hooks that make sense with no role identity. See context/core.md § Loop Settings Bundle.
LOOP_BUNDLE_IDS = frozenset(
    {
        "no-cat-pipe",
        "no-git-stash",
        "no-python-json",
        "clean-tree-before-ship",
        "build-no-success-before-commit",
        "build-agent-app-confinement",
        "build-worker-cwd-guard",
        "curator-learning-committed",
    }
)


def dumps_compact(obj, indent=2, print_width=80):
    """json.dumps with indent=2 but keeps flat string-only arrays on one line when they fit within print_width."""
    raw = json.dumps(obj, indent=indent)

    def collapse_if_fits(m):
        collapsed = "[" + ", ".join(s.strip() for s in m.group(1).split(",\n")) + "]"
        # Measure indent of the opening bracket by looking at chars before the match
        start = m.start()
        line_start = raw.rfind("\n", 0, start) + 1
        indent_len = start - line_start
        if indent_len + len(collapsed) <= print_width:
            return collapsed
        return m.group(0)

    # Collapse arrays that contain only quoted strings (no nested objects/arrays)
    return re.sub(
        r'\[\n\s+("(?:[^"\\]|\\.)*"(?:,\n\s+"(?:[^"\\]|\\.)*")*)\n\s+\]',
        collapse_if_fits,
        raw,
    )

REQUIRED_FIELDS = {"event", "matcher", "surface", "signal", "role"}
VALID_SURFACES = {"user_global", "per_call_inspector", "both"}
VALID_SIGNALS = {"AGENT_TYPE", "CLAUDE_ROLE", "CLAUDE_ROLE_FAMILY", "none"}
VALID_HARNESSES = {"claude_code", "pi"}

# Hook events managed entirely by manifests — regenerated from script headers.
MANIFEST_DRIVEN_EVENTS = {"PreToolUse", "SubagentStop", "Stop", "PostToolUseFailure"}

# Hook events with inline commands — preserved verbatim from existing settings.json.
# WorktreeCreate/WorktreeRemove are preserved here because they use inline script
# paths (same as SessionStart/End) rather than HOOK-MANIFEST-driven generation.
PRESERVED_EVENTS = {"PostToolUse", "UserPromptSubmit", "SessionStart", "SessionEnd",
                    "WorktreeCreate", "WorktreeRemove"}

# Canonical event ordering in output settings.json.
EVENT_ORDER = [
    "PostToolUse",
    "PostToolUseFailure",
    "UserPromptSubmit",
    "SessionStart",
    "SessionEnd",
    "WorktreeCreate",
    "WorktreeRemove",
    "Stop",
    "SubagentStop",
    "PreToolUse",
]


def parse_manifest(script_path: Path) -> dict:
    """Parse HOOK-MANIFEST header block from a .sh file.

    Returns dict with keys: event, matcher, surface, signal, role, filename.
    Exits non-zero if required fields are missing or malformed.
    """
    content = script_path.read_text()
    lines = content.splitlines()

    in_manifest = False
    fields: dict = {}
    for line in lines:
        stripped = line.strip()
        if stripped == "# HOOK-MANIFEST:":
            in_manifest = True
            continue
        if in_manifest:
            m = re.match(r"^#\s+(\w+):\s+(.+)$", stripped)
            if m:
                key = m.group(1)
                val = m.group(2).strip()
                if key in REQUIRED_FIELDS:
                    fields[key] = val
                elif key == "harnesses":
                    fields["harnesses"] = val
                elif key == "timeout":
                    fields["timeout"] = val
                # Continue scanning for optional fields (harnesses may follow required).
            elif stripped == "#" or stripped == "":
                # Blank comment line or empty line → end of manifest key-value block.
                # Stop here to avoid parsing prose comment lines that may accidentally
                # match the key: value regex and overwrite already-parsed fields.
                break
            elif not stripped.startswith("#"):
                # Non-comment line → manifest block ended
                break

    missing = REQUIRED_FIELDS - set(fields.keys())
    if missing:
        print(
            f"ERROR: {script_path.name} is missing HOOK-MANIFEST fields: {sorted(missing)}",
            file=sys.stderr,
        )
        sys.exit(1)

    if fields["surface"] not in VALID_SURFACES:
        print(
            f"ERROR: {script_path.name} has invalid surface '{fields['surface']}'. Must be one of: {VALID_SURFACES}",
            file=sys.stderr,
        )
        sys.exit(1)

    if fields["signal"] not in VALID_SIGNALS:
        print(
            f"ERROR: {script_path.name} has invalid signal '{fields['signal']}'. Must be one of: {VALID_SIGNALS}",
            file=sys.stderr,
        )
        sys.exit(1)

    # Coerce optional timeout field to int.
    if "timeout" in fields:
        raw_timeout = fields["timeout"]
        try:
            fields["timeout"] = int(raw_timeout)
        except ValueError:
            print(
                f"ERROR: {script_path.name} has non-integer timeout '{raw_timeout}'",
                file=sys.stderr,
            )
            sys.exit(1)

    # Parse and validate optional harnesses field.
    # "all" or absent → None (ships everywhere, default).
    # Explicit list (e.g. "claude_code") → list of tokens.
    if "harnesses" in fields:
        raw_val = fields["harnesses"]
        if raw_val.strip() == "all":
            fields["harnesses"] = None  # "all" is shorthand for ships-everywhere
        else:
            tokens = [t.strip() for t in raw_val.split(",")]
            invalid = [t for t in tokens if t not in VALID_HARNESSES]
            if invalid:
                print(
                    f"ERROR: {script_path.name} has invalid harnesses tokens: {invalid}. Must be from: {VALID_HARNESSES} or 'all'",
                    file=sys.stderr,
                )
                sys.exit(1)
            fields["harnesses"] = tokens
    else:
        fields["harnesses"] = None  # None = ships everywhere (default)

    fields["filename"] = script_path.name
    return fields


def validate_role_match(script_path: Path, manifest: dict) -> None:
    """Verify that literal role values appear in script body as guard patterns.

    For literal role values (no *, |, not in {*, all}):
      - body must contain [ "$AGENT_TYPE" = "<literal>" ]
        OR case "$AGENT_TYPE" in ... <literal>) ;;
    For glob roles (planner-*, developer-*):
      - body must contain case "$AGENT_TYPE" in <glob>) ;;
        OR printf '%s' "$AGENT_TYPE" | grep -qE '^<prefix>-'
    For wildcard roles (*, all):
      - no check required.
    Exits non-zero on mismatch (prints script name + pattern detail).
    """
    signal = manifest["signal"]
    # Only validate AGENT_TYPE signal hooks — others use CLAUDE_ROLE etc.
    if signal != "AGENT_TYPE":
        return

    content = script_path.read_text()
    role_raw = manifest["role"]

    # Split multi-value roles on |
    role_tokens = [t.strip() for t in role_raw.split("|")]

    for token in role_tokens:
        # Universal wildcards — no body check needed
        if token in ("*", "all"):
            continue

        # Glob role (ends with -*)
        if token.endswith("-*"):
            prefix = token[:-2]  # strip trailing -*
            # Accept: case ... in <prefix>-*) or grep -qE '^<prefix>-'
            glob_case = f"case \"$AGENT_TYPE\" in"
            glob_pattern = f"{prefix}-"
            if glob_case not in content or glob_pattern not in content:
                # Also accept grep-based guard
                grep_pattern = f"'^{prefix}-'"
                if grep_pattern not in content and glob_pattern not in content:
                    print(
                        f"ERROR: {script_path.name} declares role: {token} (glob) but body "
                        f"does not contain case \"$AGENT_TYPE\" in ... {prefix}-*) or grep '^{prefix}-'",
                        file=sys.stderr,
                    )
                    sys.exit(1)
            continue

        # Literal role with | — multi-case, expect case statement or helper fn
        if "|" in role_raw:
            # Each token in a multi-value role must appear in a case statement,
            # OR the hook uses require_inspector_agent_type (covers all inspector roles).
            # Case patterns can be: token) OR token | othertoken)
            inspector_fn = "require_inspector_agent_type"
            token_in_case = f'{token})' in content or f'{token} |' in content or f'{token} )' in content
            if (
                f'"{token}"' not in content
                and not token_in_case
                and not ("inspector" in token and inspector_fn in content)
            ):
                print(
                    f"ERROR: {script_path.name} declares role: {token} but body "
                    f"does not contain \"{token}\" or {token}) in a case statement",
                    file=sys.stderr,
                )
                sys.exit(1)
            continue

        # Single literal role — accept [ "$AGENT_TYPE" = "<literal>" ] (equality),
        # [ "$AGENT_TYPE" != "<literal>" ] (inequality guard), case statement,
        # or require_inspector_agent_type (for inspector roles)
        eq_check = f'[ "$AGENT_TYPE" = "{token}" ]'
        ne_check = f'[ "$AGENT_TYPE" != "{token}" ]'
        case_check = f'{token})'
        inspector_fn = "require_inspector_agent_type"
        if (
            eq_check not in content
            and ne_check not in content
            and case_check not in content
            and not ("inspector" in token and inspector_fn in content)
        ):
            print(
                f"ERROR: {script_path.name} declares role: {token} but body "
                f"does not contain [ \"$AGENT_TYPE\" = \"{token}\" ] or {token}) in a case statement",
                file=sys.stderr,
            )
            sys.exit(1)


def validate_signal(script_path: Path, manifest: dict) -> None:
    """Verify declared signal appears in script body.

    Exits non-zero if signal declared but not referenced in body.

    Signal semantics:
      CLAUDE_ROLE         — body must reference CLAUDE_ROLE literal.
      CLAUDE_ROLE_FAMILY  — body must call resolve_role() or is_build_mode() (from _role.sh);
                            supports CLAUDE_ROLE, PI_ROLE with unified precedence.
      AGENT_TYPE          — body must reference AGENT_TYPE or require_inspector_agent_type.
      none                — no signal check.
    """
    signal = manifest["signal"]
    if signal == "none":
        return

    content = script_path.read_text()
    if signal == "AGENT_TYPE":
        if "AGENT_TYPE" not in content and "require_inspector_agent_type" not in content:
            print(
                f"ERROR: {script_path.name} declares signal: AGENT_TYPE but body does not reference AGENT_TYPE or require_inspector_agent_type",
                file=sys.stderr,
            )
            sys.exit(1)
    elif signal == "CLAUDE_ROLE":
        if "CLAUDE_ROLE" not in content:
            print(
                f"ERROR: {script_path.name} declares signal: CLAUDE_ROLE but body does not reference CLAUDE_ROLE",
                file=sys.stderr,
            )
            sys.exit(1)
    elif signal == "CLAUDE_ROLE_FAMILY":
        if "resolve_role" not in content and "is_build_mode" not in content:
            print(
                f"ERROR: {script_path.name} declares signal: CLAUDE_ROLE_FAMILY but body does not call resolve_role or is_build_mode (sourced from _role.sh)",
                file=sys.stderr,
            )
            sys.exit(1)
def collect_hooks(hooks_dir: Path) -> list:  # type: ignore[type-arg]
    """Find all .sh files (excluding _test.sh, run-tests.sh, and _*.sh helpers) and parse manifests.

    Files starting with '_' are library helpers sourced by hook scripts, not registered hooks.
    Canonical example: _role.sh (shared resolve_role() helper).
    """
    hooks = []
    for sh_file in sorted(hooks_dir.glob("*.sh")):
        if sh_file.name.endswith("_test.sh"):
            continue
        if sh_file.name == "run-tests.sh":
            continue
        # Skip library helpers: files whose basename starts with '_'.
        # These are sourced by hook scripts and must not appear in settings.json.
        if sh_file.name.startswith("_"):
            continue
        manifest = parse_manifest(sh_file)
        validate_signal(sh_file, manifest)
        validate_role_match(sh_file, manifest)
        hooks.append(manifest)
    return hooks


def load_registry(registry_path: Path) -> list:  # type: ignore[type-arg]
    """Load registry YAML via yq → JSON → Python list.

    Mirrors enforcement_compiler.load_registry so no duplicate yq logic.
    """
    try:
        result = subprocess.run(
            ["yq", "-o=json", ".", str(registry_path)],
            capture_output=True,
            text=True,
            check=True,
        )
    except FileNotFoundError:
        sys.exit("ERROR: yq not found on PATH. Install with: brew install yq")
    except subprocess.CalledProcessError as e:
        sys.exit(f"ERROR: yq failed: {e.stderr}")

    try:
        data = json.loads(result.stdout)
    except json.JSONDecodeError as e:
        sys.exit(f"ERROR: JSON parse failed: {e}")

    if not isinstance(data, list):
        sys.exit("ERROR: registry.yaml must be a YAML list")

    return data


def render_header(entry: dict) -> str:
    """Render a canonical # HOOK-MANIFEST: block from a registration registry entry.

    Token mapping:
      registry tool_guard → header matcher
      registry claude     → header claude_code

    rationale field (optional):
      Single-line: emitted as "# rationale: <text>"
      Multi-line (newlines in value): first line on "# rationale:" line, subsequent
        lines prefixed with "#   " (three spaces) to match the committed header style.

    Returns the complete header block as a string (no trailing newline after final "#").
    """
    harnesses_raw = entry.get("harnesses", "all")
    # Normalise registry enum 'claude' → header token 'claude_code'
    if harnesses_raw == "claude":
        harnesses_header = "claude_code"
    elif harnesses_raw == "all":
        harnesses_header = "all"
    elif harnesses_raw == "pi":
        harnesses_header = "pi"
    else:
        # Comma-separated list — map each token
        tokens = [t.strip() for t in str(harnesses_raw).split(",")]
        mapped = ["claude_code" if t == "claude" else t for t in tokens]
        harnesses_header = ", ".join(mapped)

    # registry tool_guard → header matcher
    matcher = entry.get("tool_guard", "*")

    lines = [
        "# HOOK-MANIFEST:",
        f"# event: {entry['event']}",
        f"# matcher: {matcher}",
        f"# surface: {entry['surface']}",
        f"# signal: {entry['signal']}",
        f"# role: {entry['role']}",
        f"# harnesses: {harnesses_header}",
    ]

    timeout_val = entry.get("timeout")
    if timeout_val is not None:
        lines.append(f"# timeout: {timeout_val}")

    rationale = entry.get("rationale")
    if rationale:
        rationale_lines = rationale.splitlines()
        if len(rationale_lines) == 1:
            lines.append(f"# rationale: {rationale_lines[0]}")
        else:
            lines.append(f"# rationale: {rationale_lines[0]}")
            for cont in rationale_lines[1:]:
                lines.append(f"#   {cont}")

    lines.append("# GENERATED FROM shared/enforcement/registry.yaml — DO NOT EDIT")
    # No trailing "#" — the blank comment terminator line is part of the body
    # and is preserved by inject_header's terminator-detection logic.
    return "\n".join(lines)


def inject_header(script_path: Path, header: str) -> bool:
    """Inject a rendered header into a .sh file, replacing the existing HOOK-MANIFEST block.

    Replaces the span from the line containing "# HOOK-MANIFEST:" to the first
    terminator line (blank comment "# " with nothing after, bare "#", empty line,
    or non-comment line) — exactly mirroring parse_manifest's terminator logic.

    The body (everything after the terminator) is left byte-identical.
    Uses mktemp/cmp/mv for idempotency: no write if content unchanged.

    Returns True if file was updated, False if already up to date.
    """
    content = script_path.read_text()
    lines = content.splitlines(keepends=True)

    # Locate the HOOK-MANIFEST line
    manifest_start = None
    for i, line in enumerate(lines):
        if line.strip() == "# HOOK-MANIFEST:":
            manifest_start = i
            break

    if manifest_start is None:
        print(
            f"ERROR: {script_path.name} has no # HOOK-MANIFEST: line — cannot inject",
            file=sys.stderr,
        )
        sys.exit(1)

    # Locate the terminator: scan from the line AFTER "# HOOK-MANIFEST:"
    manifest_end = None
    for i in range(manifest_start + 1, len(lines)):
        stripped = lines[i].rstrip("\n").rstrip("\r")
        # Terminator conditions matching parse_manifest lines 113-120:
        #   blank comment line (#) or empty line or non-comment line
        if stripped.rstrip() == "#" or stripped.strip() == "" or not stripped.startswith("#"):
            manifest_end = i
            break

    if manifest_end is None:
        # Manifest runs to end of file — replace everything after manifest_start
        manifest_end = len(lines)

    # Build new content: pre-manifest lines + rendered header + newline + terminator onward
    pre = "".join(lines[:manifest_start])
    post = "".join(lines[manifest_end:])
    new_content = pre + header + "\n" + post

    if new_content == content:
        return False  # already up to date — idempotent

    tmp = tempfile.NamedTemporaryFile(
        mode="w",
        suffix=".sh",
        dir=script_path.parent,
        delete=False,
    )
    try:
        tmp.write(new_content)
        tmp.flush()
        tmp.close()
        os.replace(tmp.name, script_path)
    except Exception:
        os.unlink(tmp.name)
        raise

    return True


def emit_headers(registry_path: Path, hooks_dir: Path, check_only: bool = False) -> None:
    """For every kind:registration entry in registry, inject/verify the header in its .sh.

    check_only=True: report drift but do not write (parity check mode).
    check_only=False: write updated headers (emit mode).
    """
    entries = load_registry(registry_path)
    drift_count = 0
    updated_count = 0

    for entry in entries:
        if entry.get("kind") != "registration":
            continue

        eid = entry.get("id")
        if not eid:
            print("ERROR: registration entry missing 'id'", file=sys.stderr)
            sys.exit(1)

        sh_path = hooks_dir / f"{eid}.sh"
        if not sh_path.exists():
            print(
                f"ERROR: {eid}.sh not found in {hooks_dir} — "
                "create the script before adding a registration entry",
                file=sys.stderr,
            )
            sys.exit(1)

        header = render_header(entry)

        if check_only:
            # Check what the header would become and compare
            content = sh_path.read_text()
            lines = content.splitlines(keepends=True)

            manifest_start = None
            for i, line in enumerate(lines):
                if line.strip() == "# HOOK-MANIFEST:":
                    manifest_start = i
                    break

            if manifest_start is None:
                print(f"DRIFT: {eid}.sh has no HOOK-MANIFEST line", file=sys.stderr)
                drift_count += 1
                continue

            manifest_end = None
            for i in range(manifest_start + 1, len(lines)):
                stripped = lines[i].rstrip("\n").rstrip("\r")
                if stripped.rstrip() == "#" or stripped.strip() == "" or not stripped.startswith("#"):
                    manifest_end = i
                    break
            if manifest_end is None:
                manifest_end = len(lines)

            committed_header = "".join(lines[manifest_start:manifest_end]).rstrip("\n").rstrip("\r")
            if committed_header != header:
                print(f"DRIFT: {eid}.sh header differs from registry")
                # Show a simple diff via unified diff approach
                import difflib
                diff = list(difflib.unified_diff(
                    committed_header.splitlines(keepends=True),
                    header.splitlines(keepends=True),
                    fromfile=f"{eid}.sh (committed)",
                    tofile=f"{eid}.sh (registry)",
                ))
                for dl in diff:
                    print(dl, end="")
                drift_count += 1
        else:
            updated = inject_header(sh_path, header)
            if updated:
                print(f"updated header: {sh_path}")
                updated_count += 1
            else:
                print(f"unchanged: {sh_path}")

    if check_only:
        if drift_count == 0:
            print("hook-header-parity: PASS")
        else:
            print(f"hook-header-parity: FAIL ({drift_count} drift(s))", file=sys.stderr)
            sys.exit(1)
    else:
        reg_count = sum(1 for e in entries if e.get("kind") == "registration")
        print(f"emit-headers: {updated_count} updated, {reg_count - updated_count} unchanged")


def parse_subagent_frontmatter(subagent_path: Path) -> dict:
    """Parse YAML frontmatter between `---` lines inside `{% if tool.yaml_frontmatter %}` block.

    Returns dict with at least `name` key. Exits non-zero if `name` not found.
    """
    content = subagent_path.read_text()
    lines = content.splitlines()

    in_block = False
    in_frontmatter = False
    frontmatter_lines = []

    for line in lines:
        stripped = line.strip()
        if not in_block and "{% if tool.yaml_frontmatter %}" in stripped:
            in_block = True
            continue
        if in_block and not in_frontmatter and stripped == "---":
            in_frontmatter = True
            continue
        if in_frontmatter:
            if stripped == "---":
                break
            frontmatter_lines.append(line)

    result: dict = {}
    for fl in frontmatter_lines:
        m = re.match(r"^(\w[\w-]*):\s*(.+)$", fl.strip())
        if m:
            result[m.group(1)] = m.group(2).strip()

    if "name" not in result:
        print(
            f"ERROR: {subagent_path.name} has no `name:` in YAML frontmatter",
            file=sys.stderr,
        )
        sys.exit(1)

    return result




def build_hook_entry(manifest: dict) -> dict:
    """Build a Claude Code settings.json hook entry."""
    entry = {
        "type": "command",
        "command": f"$HOME/.claude/hooks/{manifest['filename']}",
    }
    if manifest.get("timeout") is not None:
        entry["timeout"] = manifest["timeout"]
    return entry


def load_existing_settings(settings_path: Path, existing_settings_path=None) -> dict:
    """Load existing settings.json for preserved-event extraction.

    If --existing-settings is provided, read from there (used by hook-parity to
    supply the committed file as the source of preserved events while writing output
    to /tmp). Otherwise, read from settings_path itself.
    """
    source = existing_settings_path if existing_settings_path is not None else settings_path
    if source.exists():
        return json.loads(source.read_text())
    return {}


def group_by_event(hooks: list) -> dict:
    """Group hooks by event type, sorted alphabetically by filename within each event."""
    groups: dict = {}
    for h in sorted(hooks, key=lambda x: x["filename"]):
        event = h["event"]
        groups.setdefault(event, [])
        groups[event].append(h)
    return groups


def regenerate_settings(
    existing: dict, user_global_hooks: list, settings_path: Path
) -> None:
    """Regenerate the hooks section of settings.json with user_global hooks.

    Preserves all top-level non-hooks keys verbatim.
    Preserves PRESERVED_EVENTS hook entries verbatim.
    Rebuilds MANIFEST_DRIVEN_EVENTS from user_global_hooks.
    """
    # Start with a copy of everything except hooks
    settings = {k: v for k, v in existing.items() if k != "hooks"}

    existing_hooks = existing.get("hooks", {})
    new_hooks: dict = {}

    # Preserve non-manifest-driven events verbatim
    for evt in PRESERVED_EVENTS:
        if evt in existing_hooks:
            new_hooks[evt] = existing_hooks[evt]

    # Build manifest-driven events from user_global hooks
    by_event = group_by_event(user_global_hooks)

    for evt in MANIFEST_DRIVEN_EVENTS:
        if evt not in by_event:
            continue
        entries = []
        for h in by_event[evt]:
            hook_cmd = build_hook_entry(h)
            matcher = h["matcher"]

            if evt == "Stop" and matcher == "*":
                # Stop hooks with wildcard matcher: no matcher key
                entries.append({"hooks": [hook_cmd]})
            elif evt == "SubagentStop":
                entries.append({"matcher": matcher, "hooks": [hook_cmd]})
            elif evt == "PostToolUseFailure":
                entries.append({"matcher": matcher, "hooks": [hook_cmd]})
            else:
                entries.append({"matcher": matcher, "hooks": [hook_cmd]})
        new_hooks[evt] = entries

    # Assemble in canonical order
    ordered_hooks: dict = {}
    for evt in EVENT_ORDER:
        if evt in new_hooks:
            ordered_hooks[evt] = new_hooks[evt]
    # Append any remaining events not in EVENT_ORDER
    for evt in new_hooks:
        if evt not in ordered_hooks:
            ordered_hooks[evt] = new_hooks[evt]

    settings["hooks"] = ordered_hooks
    settings_path.write_text(dumps_compact(settings) + "\n")
    print(f"Wrote {settings_path}")


def write_inspector_settings(per_call_hooks: list, out_path: Path) -> None:
    """Write the per-call inspector settings fragment {"hooks": {...}}.

    Groups per_call_hooks by event (only PreToolUse in practice) and emits
    one {"matcher", "hooks":[entry]} per hook, matching the settings.json
    PreToolUse entry shape. Parent dir is created if absent (the generated
    output tree is gitignored and may not exist).
    """
    by_event = group_by_event(per_call_hooks)
    hooks_section: dict = {}
    for evt in EVENT_ORDER:
        if evt not in by_event:
            continue
        entries = []
        for h in by_event[evt]:
            entries.append({"matcher": h["matcher"], "hooks": [build_hook_entry(h)]})
        hooks_section[evt] = entries
    # Append any events not in EVENT_ORDER (defensive; per-call hooks are PreToolUse).
    for evt in by_event:
        if evt not in hooks_section:
            entries = [
                {"matcher": h["matcher"], "hooks": [build_hook_entry(h)]}
                for h in by_event[evt]
            ]
            hooks_section[evt] = entries
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(dumps_compact({"hooks": hooks_section}) + "\n")
    print(f"Wrote {out_path}")


def emit_loop_settings(loop_hooks: list, out_path: Path) -> None:
    """Write the Elixir orchestration-loop settings bundle {"hooks": {...}}.

    Structurally identical to write_inspector_settings: groups loop_hooks by
    event (only PreToolUse in practice) and emits one {"matcher", "hooks":[entry]}
    per hook, matching the settings.json PreToolUse entry shape. Unlike the
    per-call inspector fragment, this file IS committed — it is read directly
    by OrchestrationLoop.guard_bundle_flag!("claude_code") at loop runtime.
    """
    by_event = group_by_event(loop_hooks)
    hooks_section: dict = {}
    for evt in EVENT_ORDER:
        if evt not in by_event:
            continue
        entries = []
        for h in by_event[evt]:
            entries.append({"matcher": h["matcher"], "hooks": [build_hook_entry(h)]})
        hooks_section[evt] = entries
    # Append any events not in EVENT_ORDER (defensive; loop hooks are PreToolUse).
    for evt in by_event:
        if evt not in hooks_section:
            entries = [
                {"matcher": h["matcher"], "hooks": [build_hook_entry(h)]}
                for h in by_event[evt]
            ]
            hooks_section[evt] = entries
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(dumps_compact({"hooks": hooks_section}) + "\n")
    print(f"Wrote {out_path}")


def validate_pi_ts_handlers(pi_hooks: list, pi_extension_dir: Path) -> None:
    """Verify every Pi-targeted hook has a matching TypeScript handler.

    For each hook in pi_hooks, derives handler name = filename without .sh extension,
    then checks <pi_extension_dir>/src/hooks/<name>.ts exists.
    Exits non-zero with a descriptive message listing all missing handlers.
    """
    hooks_src_dir = pi_extension_dir / "src" / "hooks"
    missing = []
    for h in sorted(pi_hooks, key=lambda x: x["filename"]):
        name = h["filename"][:-3] if h["filename"].endswith(".sh") else h["filename"]
        ts_path = hooks_src_dir / f"{name}.ts"
        if not ts_path.exists():
            missing.append(f"  {h['filename']} → expected {ts_path}")

    if missing:
        print(
            "ERROR: Pi handler parity check FAILED. "
            f"The following {len(missing)} hook(s) have no TypeScript handler in "
            f"{hooks_src_dir}:\n" + "\n".join(missing) + "\n"
            "Add the missing .ts handler(s) before running make install.",
            file=sys.stderr,
        )
        sys.exit(1)

    print(f"Pi TS handler parity: OK ({len(pi_hooks)} hooks matched)")




def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate hook registration JSONs from HOOK-MANIFEST headers"
    )
    parser.add_argument(
        "--hooks-dir", required=True, help="Directory containing .sh hook files"
    )
    parser.add_argument(
        "--output-settings",
        help="Path to write regenerated claude-code-settings.json (required unless --emit-headers or --check-headers)",
    )
    parser.add_argument(
        "--existing-settings",
        help="Path to read existing settings from (for preserved events). Defaults to --output-settings.",
    )
    parser.add_argument(
        "--pi-extension-dir",
        help="Path to Pi extension package root (validates TS handler parity for Pi-targeted hooks)",
    )
    parser.add_argument(
        "--registry",
        help="Path to shared/enforcement/registry.yaml (required for --emit-headers / --check-headers)",
    )
    parser.add_argument(
        "--emit-headers",
        action="store_true",
        help="Inject/update HOOK-MANIFEST headers in .sh files from registry kind:registration entries",
    )
    parser.add_argument(
        "--check-headers",
        action="store_true",
        help="Verify committed .sh headers match registry kind:registration entries (parity check, no writes)",
    )
    args = parser.parse_args()

    hooks_dir = Path(args.hooks_dir)
    if not hooks_dir.is_dir():
        print(f"ERROR: --hooks-dir '{hooks_dir}' is not a directory", file=sys.stderr)
        sys.exit(1)

    # Header-only modes: emit or check, do not regenerate settings
    if args.emit_headers or args.check_headers:
        if not args.registry:
            print("ERROR: --registry is required with --emit-headers / --check-headers", file=sys.stderr)
            sys.exit(1)
        registry_path = Path(args.registry)
        if not registry_path.exists():
            print(f"ERROR: registry not found: {registry_path}", file=sys.stderr)
            sys.exit(1)
        emit_headers(registry_path, hooks_dir, check_only=args.check_headers)
        return

    # Settings-regeneration mode (default)
    if not args.output_settings:
        print("ERROR: --output-settings is required when not using --emit-headers / --check-headers", file=sys.stderr)
        sys.exit(1)

    settings_path = Path(args.output_settings)
    existing_settings_path = Path(args.existing_settings) if args.existing_settings else None

    # Collect and parse all hooks
    all_hooks = collect_hooks(hooks_dir)

    # Partition by surface
    user_global_hooks = [h for h in all_hooks if h["surface"] in ("user_global", "both")]
    per_call_hooks = [h for h in all_hooks if h["surface"] in ("per_call_inspector", "both")]

    print(
        f"Found {len(all_hooks)} hooks: {len(user_global_hooks)} user_global, {len(per_call_hooks)} per_call_inspector"
    )

    # Emit per-call inspector settings fragment (separate from user_global settings.json).
    inspector_out = Path(__file__).parent.parent / "generated" / "claude-code" / "inspector-settings.json"
    write_inspector_settings(per_call_hooks, inspector_out)

    # Emit the minimal Elixir orchestration-loop hook bundle (committed; read directly
    # by OrchestrationLoop.guard_bundle_flag!). Derived from settings_path.parent so the
    # hook-parity run (--output-settings /tmp/...) emits to /tmp, and the install run
    # (--output-settings <repo>/harnesses/claude/claude-code-settings.json) emits the
    # committed sibling file.
    loop_hooks = [h for h in user_global_hooks if h["filename"][:-3] in LOOP_BUNDLE_IDS]
    if len(loop_hooks) != len(LOOP_BUNDLE_IDS):
        found_ids = {h["filename"][:-3] for h in loop_hooks}
        missing_ids = sorted(LOOP_BUNDLE_IDS - found_ids)
        print(
            "ERROR: LOOP_BUNDLE_IDS incomplete — missing hook(s) not found among "
            f"user_global hooks in {hooks_dir}: {missing_ids}. "
            "Every loop-bundle ID must correspond to a real user_global hook.",
            file=sys.stderr,
        )
        sys.exit(1)
    loop_out = settings_path.parent / "claude-code-loop-settings.json"
    emit_loop_settings(loop_hooks, loop_out)

    # Regenerate settings.json
    existing = load_existing_settings(settings_path, existing_settings_path)
    regenerate_settings(existing, user_global_hooks, settings_path)

    # Validate Pi TS handler parity if --pi-extension-dir provided
    if args.pi_extension_dir:
        pi_hooks = [h for h in all_hooks if "pi" in (h.get("harnesses") or [])]
        validate_pi_ts_handlers(pi_hooks, Path(args.pi_extension_dir))

    print("hook_registrations.py: OK")


if __name__ == "__main__":
    main()
